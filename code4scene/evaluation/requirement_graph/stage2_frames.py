"""Unified, metadata-isolated RGB storage for RequirementGraph Stage 2.

The store is the controller-side boundary between camera acquisition and later
visual adjudication. Controller records retain poses and acquisition
provenance while downstream artifacts refer to opaque store-generated ids.

Provider frame ids are deliberately never accepted.  They may contain actor
names or other UE metadata, so every admitted frame receives a deterministic
``s2f_XXXXXX`` id generated by this store.  Stage 3 reuses the same ownership
and validation boundary through an explicitly requested ``s3f`` namespace;
the default Stage 2 wire format remains unchanged.
"""

from __future__ import annotations

import hashlib
import math
import re
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass, field, replace
from enum import Enum
from typing import Any

import numpy as np

from .contracts import CameraPose
from .stage2_contracts import CaptureShotRole, Stage2Budget

RGB_HASH_ALGORITHM = "sha256_rgb_u8_c_order_v1"
DEFAULT_VALID_FRAME_HARD_CAP = 18
DEFAULT_EVIDENCE_FRAMES_PER_TASK = 4
STAGE3_EVIDENCE_FRAMES_PER_TASK = 6
LOW_DETAIL_P999_GRADIENT_THRESHOLD = 6.0
LOW_DETAIL_MAX_GRADIENT_THRESHOLD = 12.0
_OPAQUE_FRAME_ID = re.compile(r"\A(?P<prefix>s[23]f)_[0-9]{6}\Z", re.ASCII)
_FRAME_ID_PREFIXES = frozenset({"s2f", "s3f"})
_SHOT_ROLES = frozenset(
    {
        "context",
        "close",
        "detail",
        "oblique",
        "joint",
        "collection_wide",
        "overview",
        "grid",
        "recovery",
    }
)


class FrameRejectionReason(str, Enum):
    """Controller-visible reason why a capture did not enter the valid store."""

    INVALID_SHAPE = "invalid_shape"
    INVALID_DTYPE = "invalid_dtype"
    NEAR_CONSTANT = "near_constant"
    LOW_SPATIAL_DETAIL = "low_spatial_detail"
    SEVERELY_UNDEREXPOSED = "severely_underexposed"
    SEVERELY_OVEREXPOSED = "severely_overexposed"
    NEAR_DUPLICATE = "near_duplicate"
    VALID_FRAME_CAP = "valid_frame_cap"


class FrameQualityError(ValueError):
    """A captured RGB array is not valid Stage 2 visual evidence."""

    def __init__(
        self,
        reason: FrameRejectionReason,
        detail: str,
        *,
        metrics: Mapping[str, float | int] | None = None,
    ) -> None:
        super().__init__(detail)
        self.reason = reason
        self.metrics = dict(metrics or {})


@dataclass(frozen=True, slots=True)
class FrameQuality:
    """Pixel-only health metrics retained for controller audit and selection."""

    width: int
    height: int
    minimum: int
    maximum: int
    standard_deviation: float
    mean_luminance: float
    p05_luminance: float
    p95_luminance: float
    p999_spatial_gradient: float
    maximum_spatial_gradient: float

    def __post_init__(self) -> None:
        if self.width < 1 or self.height < 1:
            raise ValueError("frame quality dimensions must be positive")
        numeric = (
            self.standard_deviation,
            self.mean_luminance,
            self.p05_luminance,
            self.p95_luminance,
            self.p999_spatial_gradient,
            self.maximum_spatial_gradient,
        )
        if not all(math.isfinite(float(value)) for value in numeric):
            raise ValueError("frame quality values must be finite")

    @property
    def contrast(self) -> int:
        return self.maximum - self.minimum

    def to_dict(self) -> dict[str, float | int]:
        return {
            "width": self.width,
            "height": self.height,
            "minimum": self.minimum,
            "maximum": self.maximum,
            "standard_deviation": self.standard_deviation,
            "mean_luminance": self.mean_luminance,
            "p05_luminance": self.p05_luminance,
            "p95_luminance": self.p95_luminance,
            "p999_spatial_gradient": self.p999_spatial_gradient,
            "maximum_spatial_gradient": self.maximum_spatial_gradient,
        }


def _readonly_owned_rgb(value: Any) -> np.ndarray:
    """Return a private C-order uint8 array which cannot alias caller memory."""

    array = np.asarray(value)
    if (
        array.ndim != 3
        or array.shape[0] < 1
        or array.shape[1] < 1
        or array.shape[2] != 3
    ):
        raise FrameQualityError(
            FrameRejectionReason.INVALID_SHAPE,
            f"RGB frame must have non-empty HxWx3 shape, got {array.shape!r}",
        )
    if array.dtype != np.uint8:
        raise FrameQualityError(
            FrameRejectionReason.INVALID_DTYPE,
            f"RGB frame must use uint8 pixels, got {array.dtype}",
        )
    owned = np.array(array, dtype=np.uint8, order="C", copy=True)
    owned.setflags(write=False)
    return owned


def validate_frame_quality(rgb: Any) -> tuple[np.ndarray, FrameQuality]:
    """Copy and validate RGB using deterministic acquisition-health checks."""

    owned = _readonly_owned_rgb(rgb)
    minimum = int(owned.min())
    maximum = int(owned.max())
    float_rgb = owned.astype(np.float32)
    standard_deviation = float(float_rgb.std())
    base_metrics: dict[str, float | int] = {
        "width": int(owned.shape[1]),
        "height": int(owned.shape[0]),
        "minimum": minimum,
        "maximum": maximum,
        "standard_deviation": standard_deviation,
    }
    if maximum - minimum < 2 or standard_deviation < 0.25:
        raise FrameQualityError(
            FrameRejectionReason.NEAR_CONSTANT,
            "RGB frame is black/near-constant or otherwise invalid "
            f"(range={minimum}..{maximum}, std={standard_deviation:.4f})",
            metrics=base_metrics,
        )

    luminance = (
        0.2126 * float_rgb[:, :, 0]
        + 0.7152 * float_rgb[:, :, 1]
        + 0.0722 * float_rgb[:, :, 2]
    )
    mean_luminance = float(luminance.mean())
    p05_luminance = float(np.percentile(luminance, 5.0))
    p95_luminance = float(np.percentile(luminance, 95.0))
    base_metrics.update(
        mean_luminance=mean_luminance,
        p05_luminance=p05_luminance,
        p95_luminance=p95_luminance,
    )
    if mean_luminance < 4.0 and p95_luminance < 12.0:
        raise FrameQualityError(
            FrameRejectionReason.SEVERELY_UNDEREXPOSED,
            "RGB frame is severely underexposed/near-black "
            f"(mean_luma={mean_luminance:.3f}, p95_luma={p95_luminance:.3f})",
            metrics=base_metrics,
        )
    # Mirror the severe-underexposure guard at the bright end of the
    # luminance range.  Requiring both a near-white frame mean and a near-white
    # fifth percentile deliberately limits recovery to globally washed-out
    # captures; a legitimate bright sky, snow field, or highlight occupying
    # only part of the image remains admissible.
    if mean_luminance > 251.0 and p05_luminance > 243.0:
        raise FrameQualityError(
            FrameRejectionReason.SEVERELY_OVEREXPOSED,
            "RGB frame is severely overexposed/near-white "
            f"(mean_luma={mean_luminance:.3f}, p05_luma={p05_luminance:.3f})",
            metrics=base_metrics,
        )

    # A camera embedded in, or immediately facing, a large planar surface can
    # be normally exposed and have a broad luminance range while containing no
    # usable scene structure.  Retain a deliberately conservative guard: both
    # the 99.9th percentile and the single strongest neighbouring-pixel edge
    # must be weak.  A simple object with even a small hard silhouette remains
    # admissible, unlike a rule based on mean contrast or edge population.
    horizontal_gradient = np.abs(np.diff(luminance, axis=1)).reshape(-1)
    vertical_gradient = np.abs(np.diff(luminance, axis=0)).reshape(-1)
    spatial_gradient = np.concatenate((horizontal_gradient, vertical_gradient))
    p999_spatial_gradient = float(np.percentile(spatial_gradient, 99.9))
    maximum_spatial_gradient = float(spatial_gradient.max())
    base_metrics.update(
        p999_spatial_gradient=p999_spatial_gradient,
        maximum_spatial_gradient=maximum_spatial_gradient,
    )
    if (
        p999_spatial_gradient < LOW_DETAIL_P999_GRADIENT_THRESHOLD
        and maximum_spatial_gradient < LOW_DETAIL_MAX_GRADIENT_THRESHOLD
    ):
        raise FrameQualityError(
            FrameRejectionReason.LOW_SPATIAL_DETAIL,
            "RGB frame contains no usable spatial detail "
            f"(p99.9_gradient={p999_spatial_gradient:.3f}, "
            f"max_gradient={maximum_spatial_gradient:.3f})",
            metrics=base_metrics,
        )
    return owned, FrameQuality(
        width=int(owned.shape[1]),
        height=int(owned.shape[0]),
        minimum=minimum,
        maximum=maximum,
        standard_deviation=standard_deviation,
        mean_luminance=mean_luminance,
        p05_luminance=p05_luminance,
        p95_luminance=p95_luminance,
        p999_spatial_gradient=p999_spatial_gradient,
        maximum_spatial_gradient=maximum_spatial_gradient,
    )


def sha256_rgb_u8_c_order_v1(rgb: Any) -> str:
    """Hash exactly the canonical uint8 C-order pixel bytes."""

    canonical = _readonly_owned_rgb(rgb)
    return hashlib.sha256(canonical.tobytes(order="C")).hexdigest()


def _frame_id_prefix(value: Any) -> str:
    prefix = str(value).strip()
    if prefix not in _FRAME_ID_PREFIXES:
        raise ValueError("frame_id_prefix must be 's2f' or 's3f'")
    return prefix


def _opaque_frame_id(value: Any, *, expected_prefix: str | None = None) -> str:
    match = _OPAQUE_FRAME_ID.fullmatch(value) if isinstance(value, str) else None
    if (
        match is None
        or int(value.rsplit("_", 1)[-1]) < 1
        or (
            expected_prefix is not None
            and match.group("prefix") != _frame_id_prefix(expected_prefix)
        )
    ):
        raise ValueError(
            "judge frame_id must be an opaque store-generated "
            f"{expected_prefix or 's2f/s3f'}_XXXXXX id"
        )
    return value


def _text(value: Any, field_name: str) -> str:
    text = str(value).strip()
    if not text:
        raise ValueError(f"{field_name} must be non-empty")
    return text


def _ordered_ids(values: Iterable[Any], field_name: str) -> tuple[str, ...]:
    selected: dict[str, str] = {}
    for value in values:
        text = _text(value, field_name)
        selected.setdefault(text, text)
    return tuple(selected.values())


def _shot_role(value: Any) -> CaptureShotRole:
    try:
        return CaptureShotRole.coerce(value)
    except (TypeError, ValueError) as exc:
        raw = getattr(value, "value", value)
        raise ValueError(
            f"shot_role must be one of {sorted(_SHOT_ROLES)!r}, got {raw!r}"
        ) from exc


@dataclass(frozen=True, slots=True)
class FrameRecord:
    """Controller-only valid frame with acquisition metadata and RGB."""

    frame_id: str
    pose: CameraPose
    phase: str
    shot_role: CaptureShotRole
    task_ids: tuple[str, ...]
    actor_ids: tuple[str, ...]
    quality: FrameQuality
    rgb: np.ndarray = field(repr=False, compare=False)

    def __post_init__(self) -> None:
        object.__setattr__(self, "frame_id", _opaque_frame_id(self.frame_id))
        if not isinstance(self.pose, CameraPose):
            raise TypeError("pose must be a CameraPose")
        object.__setattr__(self, "phase", _text(self.phase, "phase"))
        object.__setattr__(self, "shot_role", _shot_role(self.shot_role))
        object.__setattr__(
            self,
            "task_ids",
            _ordered_ids(self.task_ids, "task_ids entries"),
        )
        object.__setattr__(
            self,
            "actor_ids",
            _ordered_ids(self.actor_ids, "actor_ids entries"),
        )
        if not isinstance(self.quality, FrameQuality):
            raise TypeError("quality must be FrameQuality")
        owned = _readonly_owned_rgb(self.rgb)
        if owned.shape[:2] != (self.quality.height, self.quality.width):
            raise ValueError("RGB dimensions do not match FrameQuality")
        object.__setattr__(self, "rgb", owned)

    @property
    def image_hash(self) -> str:
        return hashlib.sha256(self.rgb.tobytes(order="C")).hexdigest()

    def index_dict(self) -> dict[str, Any]:
        """Serialize controller metadata without embedding or aliasing pixels."""

        return {
            "frame_id": self.frame_id,
            "pose": self.pose.to_dict(),
            "phase": self.phase,
            "shot_role": self.shot_role.value,
            "task_ids": list(self.task_ids),
            "actor_ids": list(self.actor_ids),
            "quality": self.quality.to_dict(),
            "image_hash": self.image_hash,
            "hash_algorithm": RGB_HASH_ALGORITHM,
        }


@dataclass(frozen=True, slots=True)
class FrameAdmission:
    """Result of one attempted insertion into a :class:`FrameStore`."""

    accepted: bool
    record: FrameRecord | None = None
    rejection_reason: FrameRejectionReason | None = None
    duplicate_of_frame_id: str | None = None
    quality_metrics: Mapping[str, float | int] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if self.accepted != (self.record is not None):
            raise ValueError("accepted admissions require exactly one FrameRecord")
        if self.accepted and self.rejection_reason is not None:
            raise ValueError("accepted admissions cannot have a rejection reason")
        if not self.accepted and self.rejection_reason is None:
            raise ValueError("rejected admissions require a rejection reason")
        if self.duplicate_of_frame_id is not None:
            object.__setattr__(
                self,
                "duplicate_of_frame_id",
                _opaque_frame_id(self.duplicate_of_frame_id),
            )


def _budget_int(
    budget: Any | None,
    name: str,
    default: int,
) -> int:
    value = default if budget is None else getattr(budget, name, default)
    if isinstance(value, bool) or not isinstance(value, int) or value < 1:
        raise ValueError(f"{name} must be a positive integer")
    return value


def _near_duplicate(left: np.ndarray, right: np.ndarray, threshold: float) -> bool:
    if left.shape != right.shape:
        return False
    stride_y = max(1, left.shape[0] // 24)
    stride_x = max(1, left.shape[1] // 24)
    left_sample = left[::stride_y, ::stride_x].astype(np.int16)
    right_sample = right[::stride_y, ::stride_x].astype(np.int16)
    return float(np.mean(np.abs(left_sample - right_sample))) < threshold


def _pose_diversity(left: CameraPose, right: CameraPose) -> float:
    location = math.dist(left.location_cm, right.location_cm) / 1000.0

    def angular_distance(a: float, b: float) -> float:
        return abs((a - b + 180.0) % 360.0 - 180.0) / 180.0

    angle = (
        angular_distance(left.yaw, right.yaw) + abs(left.pitch - right.pitch) / 180.0
    )
    return location + angle


class FrameStore:
    """Own valid RGB frames and enforce namespace-specific evidence budgets."""

    def __init__(
        self,
        budget: Stage2Budget | None = None,
        *,
        valid_frame_hard_cap: int | None = None,
        evidence_frames_per_task: int | None = None,
        near_duplicate_mae_threshold: float = 0.5,
        frame_id_prefix: str = "s2f",
    ) -> None:
        prefix = _frame_id_prefix(frame_id_prefix)
        default_valid_cap = (
            DEFAULT_VALID_FRAME_HARD_CAP if prefix == "s2f" else 10
        )
        budget_valid_name = (
            "max_valid_frames"
            if prefix == "s2f"
            else "max_valid_exploration_frames"
        )
        default_evidence_cap = (
            DEFAULT_EVIDENCE_FRAMES_PER_TASK
            if prefix == "s2f"
            else STAGE3_EVIDENCE_FRAMES_PER_TASK
        )
        budget_evidence_name = (
            "max_evidence_frames_per_task"
            if prefix == "s2f"
            else "max_portfolio_frames"
        )
        cap = (
            _budget_int(budget, budget_valid_name, default_valid_cap)
            if valid_frame_hard_cap is None
            else valid_frame_hard_cap
        )
        evidence_cap = (
            _budget_int(
                budget,
                budget_evidence_name,
                default_evidence_cap,
            )
            if evidence_frames_per_task is None
            else evidence_frames_per_task
        )
        for name, value in (
            ("valid_frame_hard_cap", cap),
            ("evidence_frames_per_task", evidence_cap),
        ):
            if isinstance(value, bool) or not isinstance(value, int) or value < 1:
                raise ValueError(f"{name} must be a positive integer")
        if (
            not math.isfinite(float(near_duplicate_mae_threshold))
            or near_duplicate_mae_threshold <= 0
        ):
            raise ValueError("near_duplicate_mae_threshold must be finite and > 0")
        self.frame_id_prefix = prefix
        self.valid_frame_hard_cap = cap
        # Defaults remain four Stage 2 / six Stage 3 frames, but an explicit or
        # graph-derived larger budget must not be silently truncated here.
        # Acquisition and model-request policies own their respective bounds.
        self.evidence_frames_per_task = evidence_cap
        self.near_duplicate_mae_threshold = float(near_duplicate_mae_threshold)
        self._records: list[FrameRecord] = []
        self._by_id: dict[str, FrameRecord] = {}
        self._next_frame_number = 1
        self._rejections: list[FrameAdmission] = []

    def __len__(self) -> int:
        return len(self._records)

    @property
    def records(self) -> tuple[FrameRecord, ...]:
        return tuple(self._records)

    @property
    def rejections(self) -> tuple[FrameAdmission, ...]:
        return tuple(self._rejections)

    @property
    def valid_frame_count(self) -> int:
        return len(self._records)

    def _new_frame_id(self) -> str:
        if self._next_frame_number > 999_999:
            raise RuntimeError(
                f"opaque {self.frame_id_prefix} frame id space exhausted"
            )
        frame_id = f"{self.frame_id_prefix}_{self._next_frame_number:06d}"
        self._next_frame_number += 1
        return frame_id

    def _reject(
        self,
        reason: FrameRejectionReason,
        *,
        duplicate_of_frame_id: str | None = None,
        quality_metrics: Mapping[str, float | int] | None = None,
    ) -> FrameAdmission:
        admission = FrameAdmission(
            accepted=False,
            rejection_reason=reason,
            duplicate_of_frame_id=duplicate_of_frame_id,
            quality_metrics=dict(quality_metrics or {}),
        )
        self._rejections.append(admission)
        return admission

    def admit(
        self,
        rgb: Any,
        *,
        pose: CameraPose,
        phase: str,
        shot_role: CaptureShotRole | str,
        task_ids: Iterable[str] = (),
        actor_ids: Iterable[str] = (),
    ) -> FrameAdmission:
        """Validate and admit a frame, or return an auditable rejection."""

        if not isinstance(pose, CameraPose):
            raise TypeError("pose must be a CameraPose")
        normalized_phase = _text(phase, "phase")
        normalized_role = _shot_role(shot_role)
        normalized_tasks = _ordered_ids(task_ids, "task_ids entries")
        normalized_actors = _ordered_ids(actor_ids, "actor_ids entries")
        try:
            owned, quality = validate_frame_quality(rgb)
        except FrameQualityError as exc:
            return self._reject(exc.reason, quality_metrics=exc.metrics)

        for existing in self._records:
            if _near_duplicate(
                owned,
                existing.rgb,
                self.near_duplicate_mae_threshold,
            ):
                self.associate(
                    existing.frame_id,
                    task_ids=normalized_tasks,
                    actor_ids=normalized_actors,
                )
                return self._reject(
                    FrameRejectionReason.NEAR_DUPLICATE,
                    duplicate_of_frame_id=existing.frame_id,
                    quality_metrics=quality.to_dict(),
                )

        if len(self._records) >= self.valid_frame_hard_cap:
            return self._reject(
                FrameRejectionReason.VALID_FRAME_CAP,
                quality_metrics=quality.to_dict(),
            )

        record = FrameRecord(
            frame_id=self._new_frame_id(),
            pose=pose,
            phase=normalized_phase,
            shot_role=normalized_role,
            task_ids=normalized_tasks,
            actor_ids=normalized_actors,
            quality=quality,
            rgb=owned,
        )
        self._records.append(record)
        self._by_id[record.frame_id] = record
        return FrameAdmission(accepted=True, record=record)

    def add_frame(self, *args: Any, **kwargs: Any) -> FrameRecord | None:
        """Convenience wrapper returning the record only when newly admitted."""

        return self.admit(*args, **kwargs).record

    def admit_captured_frame(
        self,
        captured: Any,
        *,
        shot_role: CaptureShotRole | str,
        task_ids: Iterable[str] = (),
        actor_ids: Iterable[str] = (),
        phase: str | None = None,
    ) -> FrameAdmission:
        """Admit a runtime capture while intentionally ignoring its frame id."""

        pose = getattr(captured, "pose", None)
        if not isinstance(pose, CameraPose):
            raise TypeError("captured frame must expose a CameraPose")
        converter = getattr(captured, "as_rgb_array", None)
        rgb = converter() if callable(converter) else getattr(captured, "rgb", None)
        selected_phase = (
            phase if phase is not None else getattr(captured, "phase", None)
        )
        return self.admit(
            rgb,
            pose=pose,
            phase=_text(selected_phase, "phase"),
            shot_role=shot_role,
            task_ids=task_ids,
            actor_ids=actor_ids,
        )

    def add_captured_frame(self, *args: Any, **kwargs: Any) -> FrameRecord | None:
        return self.admit_captured_frame(*args, **kwargs).record

    def associate(
        self,
        frame_id: str,
        *,
        task_ids: Iterable[str] = (),
        actor_ids: Iterable[str] = (),
    ) -> FrameRecord:
        """Attach additional controller-only consumers to an existing RGB."""

        record = self.get(frame_id)
        merged_tasks = _ordered_ids(
            (*record.task_ids, *_ordered_ids(task_ids, "task_ids entries")),
            "task_ids entries",
        )
        merged_actors = _ordered_ids(
            (*record.actor_ids, *_ordered_ids(actor_ids, "actor_ids entries")),
            "actor_ids entries",
        )
        if merged_tasks == record.task_ids and merged_actors == record.actor_ids:
            return record
        updated = replace(
            record,
            task_ids=merged_tasks,
            actor_ids=merged_actors,
        )
        index = next(
            index
            for index, candidate in enumerate(self._records)
            if candidate.frame_id == frame_id
        )
        self._records[index] = updated
        self._by_id[frame_id] = updated
        return updated

    def get(self, frame_id: str) -> FrameRecord:
        key = _opaque_frame_id(frame_id, expected_prefix=self.frame_id_prefix)
        try:
            return self._by_id[key]
        except KeyError:
            stage = "Stage 2" if self.frame_id_prefix == "s2f" else "Stage 3"
            raise KeyError(f"unknown {stage} frame id: {key}") from None

    def frame_index(self) -> dict[str, Any]:
        """Return the JSON artifact payload; RGB pixels are never serialized."""

        reason_counts: dict[str, int] = {}
        for rejection in self._rejections:
            assert rejection.rejection_reason is not None
            reason = rejection.rejection_reason.value
            reason_counts[reason] = reason_counts.get(reason, 0) + 1
        return {
            "schema_version": "1.0",
            "hash_algorithm": RGB_HASH_ALGORITHM,
            "valid_frame_hard_cap": self.valid_frame_hard_cap,
            "valid_frame_count": len(self._records),
            "rejected_frame_count": len(self._rejections),
            "rejection_counts": dict(sorted(reason_counts.items())),
            "frames": [record.index_dict() for record in self._records],
        }

    def select_records_for_task(
        self,
        task_id: str,
        *,
        limit: int | None = None,
        preferred_shot_roles: Sequence[CaptureShotRole | str] = (),
    ) -> tuple[FrameRecord, ...]:
        """Select task-owned evidence, followed by neutral scene context.

        A focus frame captured for another requirement is not admissible merely
        because it happens to exist in the same scene.  Shared pixels are reused
        only when the capture controller explicitly associated the frame with
        this task (for example, two attributes of the same actor).  Overview and
        grid frames remain eligible as context, but cannot masquerade as a
        target view.
        """

        selected_task_id = _text(task_id, "task_id")
        selected_limit = self.evidence_frames_per_task if limit is None else limit
        if (
            isinstance(selected_limit, bool)
            or not isinstance(selected_limit, int)
            or selected_limit < 0
        ):
            raise ValueError("limit must be a non-negative integer")
        selected_limit = min(
            selected_limit,
            self.evidence_frames_per_task,
        )
        if selected_limit == 0:
            return ()
        preferred = tuple(
            dict.fromkeys(_shot_role(value) for value in preferred_shot_roles)
        )
        preferred_rank = {
            value: len(preferred) - index for index, value in enumerate(preferred)
        }
        order = {record.frame_id: index for index, record in enumerate(self._records)}
        global_roles = {CaptureShotRole.OVERVIEW, CaptureShotRole.GRID}
        remaining = [
            record
            for record in self._records
            if selected_task_id in record.task_ids
            or record.shot_role in global_roles
        ]
        chosen: list[FrameRecord] = []
        chosen_roles: set[CaptureShotRole] = set()

        while remaining and len(chosen) < selected_limit:

            def score(record: FrameRecord) -> tuple[float, ...]:
                associated = float(selected_task_id in record.task_ids)
                targeted = float(
                    associated
                    and bool(record.actor_ids)
                    and record.shot_role not in global_roles
                )
                role_preference = float(preferred_rank.get(record.shot_role, 0))
                novel_role = float(record.shot_role not in chosen_roles)
                pose_diversity = (
                    min(_pose_diversity(record.pose, value.pose) for value in chosen)
                    if chosen
                    else 0.0
                )
                return (
                    targeted,
                    associated,
                    role_preference,
                    novel_role,
                    pose_diversity,
                    record.quality.standard_deviation,
                    float(-order[record.frame_id]),
                )

            winner = max(remaining, key=score)
            chosen.append(winner)
            chosen_roles.add(winner.shot_role)
            remaining.remove(winner)
        return tuple(chosen)

